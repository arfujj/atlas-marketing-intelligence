"""Generate docs/data-dictionary.md from the built warehouse, dbt YAML and the metric layer.

Run after `make build`:  uv run python scripts/data_dictionary.py
Tables and column types come from the DuckDB file itself, so the dictionary cannot drift from
what the dbt models actually produce; descriptions come from the dbt YAML.
"""

from __future__ import annotations

import glob
from pathlib import Path

import duckdb
import yaml

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "serving" / "atlas.duckdb"
OUT = ROOT / "docs" / "data-dictionary.md"

WORKSPACE = {
    "halden": "Halden Coffee Works · **Simulated** (fictional company)",
    "ga4": "Google Merchandise Store · **Observed** (GA4 public sample)",
}


def _dbt_docs() -> dict[str, dict]:
    docs: dict[str, dict] = {}
    for f in glob.glob(str(ROOT / "dbt" / "models" / "**" / "*.yml"), recursive=True):
        for m in (yaml.safe_load(open(f)) or {}).get("models", []):
            docs[m["name"]] = {
                "description": " ".join((m.get("description") or "").split()),
                "columns": {c["name"]: " ".join((c.get("description") or "").split())
                            for c in m.get("columns", [])},
                "tests": sorted({(t if isinstance(t, str) else next(iter(t)))
                                 for c in m.get("columns", [])
                                 for t in (c.get("data_tests") or c.get("tests") or [])}),
            }
    return docs


def _metrics() -> list[dict]:
    out = []
    for f in sorted(glob.glob(str(ROOT / "src" / "atlas" / "metrics" / "definitions" / "*.yml"))):
        spec = yaml.safe_load(open(f))
        for m in spec.get("metrics", []):
            out.append({**m, "workspace": spec.get("workspace", Path(f).stem)})
    return out


def _formula(m: dict) -> str:
    if m.get("type") == "ratio" or m.get("type") == "trailing":
        f = f"{m.get('numerator')} / {m.get('denominator')}"
        if m.get("window_weeks"):
            f += f" (trailing {m['window_weeks']} weeks)"
        return f
    return m.get("expression", "")


def main() -> None:
    con = duckdb.connect(str(DB), read_only=True)
    rows = con.execute("""
        select table_schema, table_name, column_name, data_type, ordinal_position
        from information_schema.columns
        where table_schema not in ('information_schema', 'pg_catalog', 'main')
        order by table_schema, table_name, ordinal_position
    """).fetchall()
    counts = {
        (s, t): con.execute(f'select count(*) from "{s}"."{t}"').fetchone()[0]
        for s, t in {(r[0], r[1]) for r in rows}
    }
    docs = _dbt_docs()

    tables: dict[tuple[str, str], list[tuple[str, str]]] = {}
    for schema, table, col, dtype, _ in rows:
        tables.setdefault((schema, table), []).append((col, dtype))

    lines = [
        "# Data dictionary",
        "",
        "*Generated by `scripts/data_dictionary.py` from `data/serving/atlas.duckdb`, the dbt YAML "
        "and the metric layer. Do not edit by hand. Row counts are for the flagship build "
        "(Halden seed 20261023; GA4 extract of 2026-10-23).*",
        "",
        "The workspaces are never joined. Every table belongs to exactly one of them.",
        "",
        "## Metrics",
        "",
        "| Workspace | Metric | Definition | Formula | Grain | Evidence |",
        "|---|---|---|---|---|---|",
    ]
    for m in _metrics():
        lines.append(
            f"| {m['workspace']} | **{m.get('label', m['name'])}** (`{m['name']}`) | "
            f"{' '.join(str(m.get('definition', '')).split())} | `{_formula(m)}` | "
            f"{m.get('grain', '')} | {m.get('evidence_type', '')} |"
        )

    groups = {ws: sorted(k for k in tables if k[0].split("_")[0] == ws) for ws in WORKSPACE}
    groups["ref"] = sorted(set(tables) - {k for v in groups.values() for k in v})
    for ws, ws_tables in groups.items():
        if not ws_tables:
            continue
        lines += ["", f"## {WORKSPACE.get(ws, 'Reference tables (seeds)')}", ""]
        for schema, table in ws_tables:
            d = docs.get(table, {})
            lines += [f"### `{schema}.{table}`", ""]
            if d.get("description"):
                lines += [d["description"], ""]
            meta = f"Rows: {counts[(schema, table)]:,}"
            if d.get("tests"):
                meta += " · dbt tests: " + ", ".join(f"`{t}`" for t in d["tests"])
            lines += [meta, "", "| Column | Type | Description |", "|---|---|---|"]
            for col, dtype in tables[(schema, table)]:
                lines.append(f"| `{col}` | {dtype} | {d.get('columns', {}).get(col, '')} |")
            lines.append("")

    OUT.write_text("\n".join(lines).rstrip() + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(tables)} tables, "
          f"{sum(len(v) for v in tables.values())} columns, {len(_metrics())} metrics")


if __name__ == "__main__":
    main()
