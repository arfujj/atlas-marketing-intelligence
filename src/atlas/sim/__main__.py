"""CLI: python -m atlas.sim --out data/synthetic/halden --seed 20261023

Writes the observable tables and the ground-truth tables to *separate* folders so that
downstream modelling code can be pointed at `observed/` without access to `truth/`.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

from atlas import __version__
from atlas.sim.config import default_world
from atlas.sim.world import simulate

LABEL = ("SYNTHETIC DATA — generated by the ATLAS simulator for a fictional company. "
         "Not real business data.")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="atlas.sim")
    p.add_argument("--out", type=Path, default=Path("data/synthetic/halden"))
    p.add_argument("--seed", type=int, default=20261023)
    args = p.parse_args(argv)

    cfg = default_world()
    world = simulate(cfg, seed=args.seed)
    observed, truth = args.out / "observed", args.out / "truth"
    observed.mkdir(parents=True, exist_ok=True)
    truth.mkdir(parents=True, exist_ok=True)

    tables = {
        observed / "media_weekly.parquet": world.media,
        observed / "outcomes_weekly.parquet": world.outcomes,
        observed / "calendar_weekly.parquet": world.calendar.drop(
            columns=["season_index", "trend_index"]),  # latent, not observable
        truth / "contributions_weekly.parquet": world.truth_contributions,
        truth / "channels.parquet": world.truth_channels,
    }
    for path, df in tables.items():
        df.to_parquet(path, index=False)

    manifest = {
        "label": LABEL,
        "company": cfg.company,
        "generator": f"atlas.sim {__version__}",
        "seed": args.seed,
        "config_fingerprint": cfg.fingerprint(),
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "history": {"start": str(world.weeks[world.burn_in].date()),
                    "end": str(world.weeks[-1].date()), "weeks": cfg.n_weeks},
        "tables": {str(p.relative_to(args.out)): len(df) for p, df in tables.items()},
        "config": cfg.model_dump(mode="json"),
    }
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(json.dumps({k: manifest[k] for k in ("seed", "config_fingerprint", "tables")},
                     indent=2))


if __name__ == "__main__":
    main()
