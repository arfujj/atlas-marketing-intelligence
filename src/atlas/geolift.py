"""Geo-lift (go-dark holdout) experiments in the simulated world: design, readout, power.

EVIDENCE TYPE of a readout: Experimental — but in Halden it is a *simulated* experiment
(generated by the true DGP with noise), so every readout is also labelled Simulated.

Design: regions are stratified by population weight into three strata (3, 3, 4 regions) and
one region per stratum is drawn at random for the holdout. In the holdout regions the tested
channel goes dark for `test_weeks`; all other spend stays at its trailing-13-week level.
The measurement window adds `cooldown_weeks` so that carryover lost after the test is counted.

Estimator (ratio / difference-in-differences on levels):
    r = Σ_pre y_holdout / Σ_pre y_control                    (pre-period: last 26 history weeks)
    Δy = Σ_window y_holdout − r · Σ_window y_control
Standard error: time placebo. The same estimator is applied to every 34-week window of the
history (26 pre + 8 "test", stride 2) with the same regions, where no test took place; the
spread of those placebo effects (relative to the counterfactual) is the noise of the design.

For calibration the readout is converted to national-equivalent units under the MMM's
assumption that response is proportional across regions: if the holdout carried a share f of
the channel's national spend, Δy_national = Δy / f, at national weekly spend x and Δx = −x.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass

import numpy as np
import pandas as pd
from scipy import stats

from atlas.mmm.model import LiftTest

PRE_WEEKS = 26
STRATA = (3, 3, 4)


@dataclass(frozen=True)
class GeoDesign:
    channel: str
    holdout: tuple[str, ...]
    control: tuple[str, ...]
    test_weeks: int = 6
    cooldown_weeks: int = 2

    @property
    def window(self) -> int:
        return self.test_weeks + self.cooldown_weeks


def stratified_holdout(geos: list[str], weights: list[float], seed: int,
                       per_stratum: int = 1) -> tuple[str, ...]:
    rng = np.random.default_rng([seed, 505])
    order = [g for _, g in sorted(zip(weights, geos, strict=True), reverse=True)]
    out, i = [], 0
    for size in STRATA:
        stratum = order[i:i + size]
        out += list(rng.choice(stratum, size=min(per_stratum, size), replace=False))
        i += size
    return tuple(sorted(str(g) for g in out))


def ratio_effect(y: pd.DataFrame, holdout: tuple[str, ...], pre: slice,
                 post: slice) -> tuple[float, float]:
    """y: geo × week matrix (rows geo, columns weeks). Returns (Δy, counterfactual)."""
    h = y.loc[list(holdout)].sum(axis=0).to_numpy()
    c = y.drop(index=list(holdout)).sum(axis=0).to_numpy()
    r = h[pre].sum() / c[pre].sum()
    cf = r * c[post].sum()
    return float(h[post].sum() - cf), float(cf)


def placebo_rel_sd(history: pd.DataFrame, holdout: tuple[str, ...], window: int,
                   stride: int = 2) -> tuple[float, int]:
    """SD of placebo relative effects over the history (no treatment took place)."""
    n = history.shape[1]
    rel = []
    for s in range(0, n - PRE_WEEKS - window + 1, stride):
        d, cf = ratio_effect(history, holdout, slice(s, s + PRE_WEEKS),
                             slice(s + PRE_WEEKS, s + PRE_WEEKS + window))
        rel.append(d / cf)
    return float(np.std(rel, ddof=1)), len(rel)


def geo_matrix(outcomes: pd.DataFrame, col: str = "first_order_revenue") -> pd.DataFrame:
    return outcomes.pivot_table(index="geo", columns="week_start", values=col, aggfunc="sum")


@dataclass(frozen=True)
class Readout:
    channel: str
    holdout: tuple[str, ...]
    test_weeks: int
    window_weeks: int
    delta_y: float  # measured incremental first-order revenue in holdout regions (negative)
    counterfactual: float
    se: float
    ci90: tuple[float, float]
    p_value: float
    holdout_spend_share: float
    x_national_weekly: float
    lift_test: LiftTest  # national-equivalent, for MMM calibration
    placebo_windows: int
    true_delta_y: float | None = None  # simulated worlds only (truth, for grading)

    def to_dict(self) -> dict:
        d = asdict(self)
        d["lift_test"] = asdict(self.lift_test)
        return d


def run_geolift(world, design: GeoDesign, seed: int) -> Readout:
    """Simulate the experiment with the true DGP (atlas.sim.extension) and read it out."""
    from atlas.sim.extension import extend

    chans = list(world.channels)
    ci = chans.index(design.channel)
    geos = list(world.geos)
    # Planned spend = trailing-13-week level of every channel (effective spend; there is no
    # CPC spike in the test window, so billed = effective there).
    level = world.spend[:, :, -13:].mean(axis=2)  # [C, G] USD/week
    H = design.window
    base_plan = np.repeat(level[:, :, None], H, axis=2)
    plan = base_plan.copy()
    hidx = [geos.index(g) for g in design.holdout]
    plan[ci][np.ix_(hidx, np.arange(design.test_weeks))] = 0.0

    ext = extend(world, plan, seed)
    ext0 = extend(world, base_plan, seed)  # same noise seed, no treatment: truth only
    hist = geo_matrix(world.outcomes)
    post = geo_matrix(ext.observed)
    y = pd.concat([hist.iloc[:, -PRE_WEEKS:], post], axis=1)
    dy, cf = ratio_effect(y, design.holdout, slice(0, PRE_WEEKS), slice(PRE_WEEKS, None))
    rel_sd, n_pl = placebo_rel_sd(hist, design.holdout, H)
    se = rel_sd * cf
    z = stats.norm.ppf(0.95)
    true_dy = float((geo_matrix(ext.expected) - geo_matrix(ext0.expected))
                    .loc[list(design.holdout)].to_numpy().sum())
    share = float(level[ci, hidx].sum() / level[ci].sum())
    x_nat = float(level[ci].sum())
    lt = LiftTest(channel=design.channel, x=x_nat, delta_x=-x_nat, delta_y=dy / share,
                  sigma=se / share, n_weeks=design.test_weeks,
                  source=f"simulated geo-lift, holdout {','.join(design.holdout)}")
    return Readout(channel=design.channel, holdout=design.holdout,
                   test_weeks=design.test_weeks, window_weeks=H, delta_y=dy,
                   counterfactual=cf, se=se, ci90=(dy - z * se, dy + z * se),
                   p_value=float(2 * stats.norm.sf(abs(dy / se))), holdout_spend_share=share,
                   x_national_weekly=x_nat, lift_test=lt, placebo_windows=n_pl,
                   true_delta_y=true_dy)


def design_sigma(outcomes: pd.DataFrame, media: pd.DataFrame, channel: str,
                 holdout: tuple[str, ...], test_weeks: int = 6,
                 cooldown_weeks: int = 2) -> dict:
    """Pre-test noise of a design in national-equivalent USD (for power and VOI).

    Uses only observed history: placebo relative SD × expected counterfactual revenue of the
    holdout over the window, divided by the holdout's share of the channel's spend.
    """
    hist = geo_matrix(outcomes)
    window = test_weeks + cooldown_weeks
    rel_sd, n = placebo_rel_sd(hist, holdout, window)
    recent = hist.loc[list(holdout)].iloc[:, -13:].sum(axis=0).mean() * window
    last = media[media.week_start >= media.week_start.max() - pd.Timedelta(weeks=12)]
    lv = last[last.channel == channel].groupby("geo").spend.mean()
    share = float(lv.reindex(list(holdout)).sum() / lv.sum())
    return {"sigma_national": float(rel_sd * recent / share), "rel_sd": rel_sd,
            "placebo_windows": n, "holdout_spend_share": share,
            "x_national_weekly": float(lv.sum()), "test_weeks": test_weeks,
            "window_weeks": window}


def power(effect: np.ndarray | float, sigma: float, alpha: float = 0.10) -> np.ndarray:
    """Two-sided power of a z-test for an effect of the given size (array-friendly)."""
    e = np.abs(np.asarray(effect, dtype=float))
    z = stats.norm.ppf(1 - alpha / 2)
    return stats.norm.cdf(e / sigma - z) + stats.norm.cdf(-e / sigma - z)
