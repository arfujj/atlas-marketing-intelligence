-- OBSERVED. Data-quality findings as rows, each with the value measured in this build and the
-- modelling decision it drives. The expected values are asserted by dbt tests in tests/ga4.
with pe as (select * from {{ ref('int_ga4__purchase_events_ranked') }}),
s as (select * from {{ ref('stg_ga4__sessions') }}),
items as (select * from {{ ref('stg_ga4__purchase_items') }}),
tot as (select * from {{ source('ga4', 'totals') }})
select * from (values
    ('sessions', 'Sessions (user_pseudo_id × ga_session_id)',
     (select count(*) from s)::double, (select sessions from tot)::double,
     'Session key is user_pseudo_id + ga_session_id; ga_session_id alone is not unique.'),
    ('users', 'Users (user_pseudo_id)',
     (select count(distinct user_pseudo_id) from s)::double, (select users from tot)::double,
     'Reconciles to the dataset totals.'),
    ('purchase_events', 'Raw purchase events',
     (select count(*) from pe)::double, null,
     'Raw rows are kept; revenue is computed after deduplication.'),
    ('tx_not_set', 'Purchase events with transaction_id = ''(not set)''',
     (select count(*) from pe where transaction_id_status = 'not_set')::double, null,
     'Cannot be deduplicated; excluded from deduplicated revenue and reported separately.'),
    ('tx_null', 'Purchase events with NULL transaction_id',
     (select count(*) from pe where transaction_id_status = 'null')::double, null,
     'Cannot be deduplicated; excluded from deduplicated revenue and reported separately.'),
    ('tx_duplicates', 'Purchase rows repeating an already-seen transaction_id',
     (select count(*) from pe where dedup_status = 'duplicate')::double, null,
     'Earliest event per transaction_id is kept; later rows are duplicates.'),
    ('transactions', 'Deduplicated transactions (valid ids)',
     (select count(*) from pe where dedup_status = 'kept')::double, null,
     'Grain of fct_ga4_transactions.'),
    ('revenue_naive', 'Revenue, naive sum of all purchase events (USD)',
     (select sum(purchase_revenue_usd) from pe), null,
     'Overstates revenue: double-counts duplicate events.'),
    ('revenue_dedup', 'Revenue, deduplicated valid transactions (USD)',
     (select sum(purchase_revenue_usd) from pe where dedup_status = 'kept'), null,
     'Headline revenue definition used by every GA4 mart.'),
    ('revenue_unidentified', 'Revenue on events without a usable transaction id (USD)',
     (select sum(purchase_revenue_usd) from pe where dedup_status = 'unidentified'), null,
     'Shown separately; not added to the headline.'),
    ('item_revenue_all_lines', 'Item-level revenue, all purchase item lines (USD)',
     (select sum(item_revenue_in_usd) from items), null,
     'Item lines duplicate with their events; compare to revenue_naive.'),
    ('midnight_sessions', 'Sessions spanning more than one event_date (UTC)',
     (select count(*) from s where crosses_midnight)::double, null,
     'Dated by session start; counted once.'),
    ('first_user_data_deleted', 'Sessions with first_user_source = ''(data deleted)''',
     (select count(*) from s where first_user_source = '(data deleted)')::double, null,
     'traffic_source is FIRST-USER acquisition; never used as session or last-touch source.'),
    ('first_user_other', 'Sessions with first_user_source = ''<Other>''',
     (select count(*) from s where first_user_source = '<Other>')::double, null,
     'Obfuscated by Google; grouped as Other (obfuscated).')
) as t(check_id, description, value, reference_value, decision)
